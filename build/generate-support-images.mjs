// Turns the "Buy me a coffee" button from SVG into a vector image Avalonia can
// draw - without a dependency, like the icon generator beside it.
// Run: node build/generate-support-images.mjs
//
// Avalonia has no SVG support of its own, and a package for it would be a new
// dependency for one picture. This SVG holds nothing but filled paths, though,
// and SVG path data is the same mini-language Avalonia's geometries speak. So
// each path becomes a GeometryDrawing, and the picture stays sharp at any size.
//
// Anything beyond that - a gradient, a group with a transform, text - is
// refused rather than dropped: a picture that silently loses a part is worse
// than a generator that stops.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, 'assets', 'support', 'buymeacoffee.svg');
const TARGET = join(ROOT, 'src', 'ClaudeUsageChecker.App', 'Views', 'SupportImages.axaml');

const svg = readFileSync(SOURCE, 'utf8');

const unexpected = [...svg.matchAll(/<([a-zA-Z]+)/g)]
  .map(m => m[1])
  .filter(name => name !== 'svg' && name !== 'path');
if (unexpected.length > 0) {
  throw new Error(`Only <path> elements are supported, found: ${[...new Set(unexpected)].join(', ')}`);
}

const attribute = (element, name) => element.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1];

const drawings = [...svg.matchAll(/<path\b[^>]*>/g)]
  .map(m => m[0])
  .filter(path => (attribute(path, 'fill') ?? '#000000') !== 'none')
  .map(path => {
    const fill = attribute(path, 'fill') ?? '#000000';
    const data = attribute(path, 'd');
    if (!data) {
      throw new Error('A <path> without data.');
    }

    // F0 is Avalonia's even-odd rule, F1 non-zero - SVG's default.
    const rule = attribute(path, 'fill-rule') === 'evenodd' ? 'F0' : 'F1';
    return `        <GeometryDrawing Brush="${fill}" Geometry="${rule} ${data}" />`;
  });

const xaml = `<!-- Generated by build/generate-support-images.mjs from assets/support/buymeacoffee.svg.
     Do not edit by hand; change the SVG and run the generator again. -->
<ResourceDictionary xmlns="https://github.com/avaloniaui"
                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
  <DrawingImage x:Key="BuyMeACoffeeImage">
    <DrawingImage.Drawing>
      <DrawingGroup>
${drawings.join('\n')}
      </DrawingGroup>
    </DrawingImage.Drawing>
  </DrawingImage>
</ResourceDictionary>
`;

writeFileSync(TARGET, xaml.replace(/\r\n/g, '\n'));
console.log(`${drawings.length} paths written to ${TARGET}`);
